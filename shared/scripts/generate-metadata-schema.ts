import { readFile, writeFile } from 'node:fs/promises'
import { z } from 'zod'
import { CopilotAgentModeSchema, ExternalRefSchema, ExternalRefsSchema, MetadataSchema } from '../src/schemas'

const schema = z.toJSONSchema(MetadataSchema, {
    io: 'input',
    override: ({ zodSchema, jsonSchema, path }) => {
        const definition = zodSchema._zod.def
        const customChecks = definition.checks?.filter(check => check._zod.def.check === 'custom').length ?? 0
        const expectedCustomChecks = zodSchema === ExternalRefsSchema || zodSchema === ExternalRefSchema ? 1 : 0
        if (customChecks !== expectedCustomChecks) {
            throw new Error(`Unsupported Zod refinements at ${path.join('.') || 'MetadataSchema'}`)
        }
        if (definition.type === 'pipe' && zodSchema !== CopilotAgentModeSchema.options[1]) {
            throw new Error(`Unsupported Zod pipe at ${path.join('.') || 'MetadataSchema'}`)
        }

        if (zodSchema === ExternalRefsSchema) {
            jsonSchema['x-hapi-external-refs'] = true
        }
        if (definition.type === 'record') {
            const key = definition.keyType._zod.def
            if (key.type === 'string' && !key.checks?.length) {
                // Zod ignores this key even when its value fails the record schema.
                jsonSchema.properties = { ['__proto__']: {} }
            }
        }
        if (definition.type === 'catch') {
            // Invalid input uses the fallback. Keep the inner schema visible to the drift check.
            const innerSchema = { ...jsonSchema }
            for (const key of Object.keys(jsonSchema)) delete jsonSchema[key]
            jsonSchema.anyOf = [innerSchema, {}]
        }
    },
})

schema.$comment = 'Generated by shared/scripts/generate-metadata-schema.ts from MetadataSchema.'
const output = JSON.stringify(schema, null, 2) + '\n'
const path = new URL('../../crates/hapi-wrapper-core/golden/metadata_schema.json', import.meta.url)

if (process.argv.includes('--check')) {
    if ((await readFile(path, 'utf8')).replaceAll('\r\n', '\n') !== output) {
        throw new Error('Outdated metadata schema. Run bun run gen:metadata-schema.')
    }
} else {
    await writeFile(path, output)
}
